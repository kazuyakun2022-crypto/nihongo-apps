async function main() {
  console.log("Seeding 12 Situational Scenarios...");
  const admin = await prisma.user.findFirst({
    where: { role: { in: ["admin", "super_admin"] } },
  });

  for (const s of SCENARIOS) {
    const existing = await prisma.scenario.findUnique({
      where: { sourceKey: s.sourceKey },
    });

    const data = {
      levelId: s.levelId,
      title: s.title,
      goal: s.goal,
      mascotRole: s.mascotRole,
      userRole: s.userRole,
      location: s.location,
      keigoType: s.keigoType,
      imageUrl: s.imageUrl,
      initialMessage: s.initialMessage,
      targetGrammar: s.targetGrammar,
      maxTurns: s.maxTurns,
      sortOrder: s.sortOrder,
      status: s.status,
      systemPrompt: s.systemPrompt,
      dialogueScript: s.dialogueScript,
      createdById: admin?.id,
    };

    if (existing) {
      await prisma.scenario.update({
        where: { id: existing.id },
        data,
      });
      console.log(`Updated scenario: ${s.title}`);
    } else {
      await prisma.scenario.create({
        data: {
          sourceKey: s.sourceKey,
          ...data,
        },
      });
      console.log(`Created scenario: ${s.title}`);
    }
  }

  console.log("Seeding finished successfully!");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());

